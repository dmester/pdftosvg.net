using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using PdfToSvg.SourceGenerators.Collections;
using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;

namespace PdfToSvg.SourceGenerators.LexerKeywords
{
    [Generator]
    public class LexerKeywordGenerator : IIncrementalGenerator
    {
        private const string AttributeMetadataName = "PdfToSvg.Parsing.LexerKeywordAttribute";
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var classes = context.SyntaxProvider
                .CreateSyntaxProvider(
                    (syntaxNode, _) =>
                        syntaxNode is ClassDeclarationSyntax classDeclaration &&
                        classDeclaration.HasAttribute("LexerKeywordAttribute") &&
                        classDeclaration.Modifiers.Any(modifier => modifier.IsKind(SyntaxKind.PartialKeyword)),
                    (context, _) => context.SemanticModel.GetDeclaredSymbol(context.Node) as INamedTypeSymbol)
                .Where(symbol => symbol is not null);

            var compilationAndClasses = context.CompilationProvider.Combine(classes.Collect());

            context.RegisterSourceOutput(
                compilationAndClasses,
                (sourceContext, source) => Generate(sourceContext, source.Left, source.Right!));
        }

        private static void Generate(
            SourceProductionContext context,
            Compilation compilation,
            ImmutableArray<INamedTypeSymbol> classSymbols)
        {
            var attributeSymbol = compilation.GetTypeByMetadataName(AttributeMetadataName);
            if (attributeSymbol == null)
            {
                return;
            }

            foreach (var classSymbol in classSymbols)
            {
                var keywords = GetKeywords(classSymbol, attributeSymbol);
                if (keywords.Count == 0)
                {
                    continue;
                }

                var table = CreateTable(keywords);
                var writer = new SourceWriter();
                writer.WriteLine("// <auto-generated/>");
                writer.WriteLine();
                writer.WriteLine($"namespace {classSymbol.ContainingNamespace}");

                using (writer.BeginBlock())
                {
                    var accessibility = classSymbol.DeclaredAccessibility.ToDisplayString();
                    writer.WriteLine($"{accessibility} partial class {classSymbol.Name}");

                    using (writer.BeginBlock())
                    {
                        StringHashTableGenerator.GenerateIndexes(
                            writer, "generatedFullEntryIndexes", table.FullTable.Indexes);
                        writer.WriteLine();

                        GenerateKeywordEntries(writer, table.FullTable.Entries);
                        writer.WriteLine();

                        StringHashTableGenerator.GenerateIndexes(
                            writer, "generatedMaxLengthEntryIndexes", table.MaxLengthTable.Indexes);
                        writer.WriteLine();

                        GenerateMaxLengthEntries(writer, table.MaxLengthTable.Entries);
                        writer.WriteLine();

                        GenerateConstructor(writer, classSymbol.Name, table);
                    }
                }

                var hintName = classSymbol.ToDisplayString().Replace('.', '_') + ".LexerKeywords.g.cs";
                context.AddSource(hintName, SourceText.From(writer.ToString(), Encoding.UTF8));
            }
        }

        private static IReadOnlyCollection<Keyword> GetKeywords(INamedTypeSymbol classSymbol, INamedTypeSymbol attributeSymbol)
        {
            var result = new Dictionary<string, Keyword>(StringComparer.Ordinal);

            foreach (var attribute in classSymbol.GetAttributes())
            {
                // Source we want to handle:
                // [LexerKeyword("def", Token.Def)]

                if (!SymbolEqualityComparer.Default.Equals(attribute.AttributeClass, attributeSymbol) ||
                    attribute.ConstructorArguments.Length != 2 ||
                    attribute.ConstructorArguments[0].Value is not string keywordText ||
                    attribute.ConstructorArguments[1].Type is not INamedTypeSymbol tokenType ||
                    attribute.ConstructorArguments[1].Value is null)
                {
                    continue;
                }

                var tokenValue = attribute.ConstructorArguments[1].Value;
                var tokenMember = tokenType
                    .GetMembers()
                    .OfType<IFieldSymbol>()
                    .First(field => field.HasConstantValue && Equals(field.ConstantValue, tokenValue));
                var tokenExpression =
                    tokenType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + "." + tokenMember.Name;

                result[keywordText] = new Keyword(keywordText, tokenExpression);
            }

            return result.Values;
        }

        private static GeneratedTable CreateTable(IReadOnlyCollection<Keyword> keywords)
        {
            var fullEntries = keywords
                .Select(keyword => new StringHashTableGenerator.SourceEntry<Keyword>(keyword.Text, keyword))
                .ToList();
            var fullTable = StringHashTableGenerator.CreateTable(fullEntries);

            var maxLengthEntries = GetPrefixes(keywords)
                .Select(prefix => new StringHashTableGenerator.SourceEntry<int>(prefix.Text, prefix.MaxLength))
                .ToList();
            var maxLengthTable = StringHashTableGenerator.CreateTable(
                maxLengthEntries,
                fullTable.BucketCount,
                fullTable.Multiplier,
                fullTable.ShiftCount);

            return new GeneratedTable(fullTable, maxLengthTable);
        }

        private static List<Prefix> GetPrefixes(IEnumerable<Keyword> keywords)
        {
            return keywords
                .Select(keyword => new
                {
                    Keyword = keyword,
                    PrefixLength = GetKeywordPrefixLength(keyword.Text),
                })
                .Where(item => item.PrefixLength < item.Keyword.Text.Length)
                .GroupBy(item => item.Keyword.Text.Substring(0, item.PrefixLength), StringComparer.Ordinal)
                .Select(group => new Prefix(group.Key, group.Max(item => item.Keyword.Text.Length)))
                .ToList();
        }

        private static int GetKeywordPrefixLength(string keyword)
        {
            for (var i = 0; i < keyword.Length; i++)
            {
                var ch = keyword[i];

                // Must match LexerKeywordTable.IsKeywordChar
                var isKeywordChar =
                    ch >= 'a' && ch <= 'z' ||
                    ch >= 'A' && ch <= 'Z' ||
                    ch == '*' ||
                    ch == '\'' ||
                    ch == '"';

                if (!isKeywordChar)
                {
                    return i;
                }
            }

            return keyword.Length;
        }

        private static void GenerateKeywordEntries(
            SourceWriter writer,
            IReadOnlyCollection<StringHashTableGenerator.TableEntry<Keyword>> entries)
        {
            const string Entry = "global::PdfToSvg.Collections.StringHashTable.Entry";
            const string LexerKeyword = "global::PdfToSvg.Parsing.LexerKeyword";

            writer.WriteLine($"private static readonly {Entry}<{LexerKeyword}>[] generatedFullEntries =");

            using (writer.BeginBlock(";"))
            {
                foreach (var entry in entries)
                {
                    var text = Utils.LiteralExpression(entry.Key).ToFullString();
                    writer.WriteLine("global::PdfToSvg.Collections.StringHashTable.CreateEntry(");
                    writer.WriteLine($"    {text}, {entry.HashCode},");
                    writer.WriteLine($"    new {LexerKeyword}({text}, {entry.Value.TokenExpression})),");
                }
            }
        }

        private static void GenerateMaxLengthEntries(
            SourceWriter writer,
            IReadOnlyCollection<StringHashTableGenerator.TableEntry<int>> entries)
        {
            const string Entry = "global::PdfToSvg.Collections.StringHashTable.Entry";

            writer.WriteLine($"private static readonly {Entry}<int>[] generatedMaxLengthEntries =");

            using (writer.BeginBlock(";"))
            {
                foreach (var entry in entries)
                {
                    var text = Utils.LiteralExpression(entry.Key).ToFullString();
                    writer.WriteLine("global::PdfToSvg.Collections.StringHashTable.CreateEntry(" +
                        $"{text}, {entry.HashCode}, {entry.Value}),");
                }
            }
        }

        private static void GenerateConstructor(SourceWriter writer, string className, GeneratedTable table)
        {
            writer.WriteLine($"public {className}()");
            writer.WriteLine("    : base(");
            writer.WriteLine($"        multiplier: 0x{table.FullTable.Multiplier:X8}u,");
            writer.WriteLine($"        shiftCount: {table.FullTable.ShiftCount},");
            writer.WriteLine("        fullEntryIndexes: generatedFullEntryIndexes,");
            writer.WriteLine("        fullEntries: generatedFullEntries,");
            writer.WriteLine("        maxLengthEntryIndexes: generatedMaxLengthEntryIndexes,");
            writer.WriteLine("        maxLengthEntries: generatedMaxLengthEntries)");

            using (writer.BeginBlock())
            {
            }
        }

        private sealed class Keyword(string text, string tokenExpression)
        {
            public string Text { get; } = text;
            public string TokenExpression { get; } = tokenExpression;
        }

        private sealed class Prefix(string text, int maxLength)
        {
            public string Text { get; } = text;
            public int MaxLength { get; } = maxLength;
        }

        private sealed class GeneratedTable(
            StringHashTableGenerator.Table<Keyword> fullTable,
            StringHashTableGenerator.Table<int> maxLengthTable)
        {
            public StringHashTableGenerator.Table<Keyword> FullTable { get; } = fullTable;
            public StringHashTableGenerator.Table<int> MaxLengthTable { get; } = maxLengthTable;
        }
    }
}
